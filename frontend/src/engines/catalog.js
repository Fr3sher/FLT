/* The engine catalog — ONE table of the image engines, what every screen
   derives its lists from. Read AT CALL TIME, never copied.

   The core owns its two local engines, Klein and Krea 2 Edit. Every other
   engine is a plugin's: an enabled plugin contributes its specs to the
   `engine.spec` slot (the bundled API-engines plugin does, for its three) and
   the catalog merges them in at each read. The plugins load BEFORE React
   mounts (src/plugins/loadPlugins.js), so the first render already sees them —
   and a disabled plugin's engines are offered nowhere: no card, no dropdown
   row, no key field, no Setup row. That is why every export below is a
   FUNCTION and not a constant: a list copied at import time would hold the
   core's two engines forever, whatever the plugins registered a moment later.

   Before this, four lists of engine ids lived in four files and already
   disagreed (the activity lanes did not know the newest API engine; the variation catalog
   did not know Krea), and the facts about an engine — label, order, rate,
   accent colour, which key lights it up, which probe "Save & test" runs, whether
   it counts as "one working engine" on the Setup screen — were each a table of
   their own. A plugin that brings an engine would have had to edit them all.

   PURE JS: node --test imports it (the plugin registry it reads is pure too),
   and `engine-catalog-contract.test.mjs` reads the backend's engine tables
   next to it so the two languages cannot drift (ids, order, labels, rates,
   key targets, recommended set).

   ⚠️ Engine IDS NEVER CHANGE: they are on disk (the filename tag of a generated
   image), in the database (a row's engine) and in localStorage (the workspace
   selection: `datasetGenerator`, `datasetGenerators`). Append, never rename.
   A row whose engine the catalog does not know right now — generated by a
   plugin that is off — keeps its id as its label and the NEUTRAL accent, so
   history still renders; it is simply not offered.

   Accent colours: deliberately NOT green — green already means "kept / already
   in the dataset / free" everywhere else in the app. Indigo / violet (the two
   local engines, read as a pair) stay distinguishable in a dark theme AND in
   deuteranopia; a plugin picks its own from the same rule. Class strings are
   spelled out in full because Tailwind scans source text — never build them
   by concatenation.

   Rates: Klein and Krea are local GPU time, hence free. A plugin engine whose
   lane is free under some condition (a subscription instead of a metered key)
   says so with `freeWhen({ caps, engineConfig })` — see freeEngines(). */
import { contributions } from '../plugins/registry.js'

/** The accent of an engine the catalog does not know (a plugin that is off). */
export const NEUTRAL_ACCENT = Object.freeze({
  card: 'border-border-strong bg-surface-raised ring-1 ring-border-strong',
  title: 'text-content', text: 'text-content-muted', icon: 'text-content-muted',
  pill: 'bg-surface-raised text-content-muted', dot: 'bg-border-strong',
})

/** The core's engines — the two that render on the user's own ComfyUI. */
export const CORE_ENGINE_CATALOG = [
  { id: 'klein', label: 'Klein', kind: 'local', order: 0,
    rate: 0, remote: false, billable: false, secret: null, keyTestTarget: null,
    recommended: true, modelSettingKey: null,
    settingsLabel: 'Klein (ComfyUI, local)', shortLabel: 'Klein (local)',
    setupRow: { label: 'Klein (local)',
      what: 'Generates test images in your own ComfyUI — no key, your GPU', topic: 'setup-comfyui' },
    accent: {
      card: 'border-indigo-400/60 bg-indigo-500/15 ring-1 ring-indigo-400/40',
      title: 'text-indigo-200', text: 'text-indigo-300', icon: 'text-indigo-300',
      pill: 'bg-indigo-500/25 text-indigo-200', dot: 'bg-indigo-400',
    } },
  { id: 'krea', label: 'Krea 2 Edit', kind: 'local', order: 1,
    rate: 0, remote: false, billable: false, secret: null, keyTestTarget: null,
    recommended: false, modelSettingKey: null,
    settingsLabel: 'Krea 2 Edit (ComfyUI, local)', shortLabel: 'Krea (local)',
    setupRow: null,
    accent: {
      card: 'border-violet-400/60 bg-violet-500/15 ring-1 ring-violet-400/40',
      title: 'text-violet-200', text: 'text-violet-300', icon: 'text-violet-300',
      pill: 'bg-violet-500/25 text-violet-200', dot: 'bg-violet-400',
    } },
]

const CORE_IDS = new Set(CORE_ENGINE_CATALOG.map((e) => e.id))

/** Every engine the app knows RIGHT NOW — the core's, then what the enabled
 *  plugins contribute — in canonical order (`order`). A plugin cannot redefine
 *  a core engine, and the first plugin to claim an id keeps it. */
export function engineCatalog() {
  const specs = [...CORE_ENGINE_CATALOG]
  for (const item of contributions('engine.spec')) {
    if (!item || typeof item.id !== 'string' || CORE_IDS.has(item.id)) continue
    if (specs.some((s) => s.id === item.id)) continue
    specs.push(item)
  }
  return specs.sort((a, b) => a.order - b.order)
}

/** One engine's facts, or undefined for an id the catalog does not know. */
export function engineSpec(id) { return engineCatalog().find((e) => e.id === id) }
export function engineLabel(id) { const s = engineSpec(id); return s ? s.label : id }
export function engineAccent(id) { const s = engineSpec(id); return (s && s.accent) || NEUTRAL_ACCENT }
export function engineRate(id) { const s = engineSpec(id); return s ? (s.rate || 0) : 0 }

/** Canonical engine order — drives the card order, the primary pick and the
 *  round-robin; local engines first (free, on the user's own GPU). */
export function engineIds() { return engineCatalog().map((e) => e.id) }
export function apiEngineSpecs() { return engineCatalog().filter((e) => e.kind === 'api') }
export function localEngineSpecs() { return engineCatalog().filter((e) => e.kind === 'local') }
export function apiEngineIds() { return apiEngineSpecs().map((e) => e.id) }
/** Render on the user's own GPU through ComfyUI: free, slower, serialized on
 *  one GPU, and the ONLY ones allowed to receive 🔞 shots. */
export function localEngineIds() { return localEngineSpecs().map((e) => e.id) }
/** Render somewhere else: they never hold the local ComfyUI. */
export function remoteEngineIds() { return engineCatalog().filter((e) => e.remote).map((e) => e.id) }
/** One working engine of these = a set-up install (the nav rail's "recommended"). */
export function recommendedEngineIds() { return engineCatalog().filter((e) => e.recommended).map((e) => e.id) }

export function engineLabels() { return Object.fromEntries(engineCatalog().map((e) => [e.id, e.label])) }
export function engineAccents() { return Object.fromEntries(engineCatalog().map((e) => [e.id, e.accent || NEUTRAL_ACCENT])) }
export function engineRates() { return Object.fromEntries(engineCatalog().map((e) => [e.id, e.rate || 0])) }
/** Which capability probe "Save & test" runs for an engine's key field. */
export function keyTestTargets() {
  return Object.fromEntries(engineCatalog().filter((e) => e.keyTestTarget).map((e) => [e.id, e.keyTestTarget]))
}
/** The Settings dropdown rows, API engines first as they always were listed. */
export function engineSettingsOptions() {
  return [...apiEngineSpecs(), ...localEngineSpecs()].map((e) => ({ id: e.id, label: e.settingsLabel || e.label }))
}
/** The counted capability rows of the API engines, in canonical order. */
export function apiEngineSetupRows() {
  return apiEngineSpecs().filter((e) => e.setupRow).map((e) => ({ id: e.id, ...e.setupRow }))
}

/** The engine a profile with no stored preference generates with: the first
 *  API engine (historically the first cloud engine, the workspace's useState default),
 *  else the first engine there is. Null only with an empty catalog. */
export function defaultEngineId() {
  const api = apiEngineIds()
  return api[0] || engineIds()[0] || null
}

/** The engines whose lane costs nothing for THIS run — the local ones by
 *  rate, plus any engine whose spec says its lane is free under the current
 *  capabilities and settings (`freeWhen`): a subscription lane spends plan
 *  quota, not dollars. `engineConfig` is the config's `engines`
 *  section as the screen read it. */
export function freeEngines({ caps = {}, engineConfig = {} } = {}) {
  return engineCatalog()
    .filter((e) => typeof e.freeWhen === 'function' && e.freeWhen({ caps: caps || {}, engineConfig: engineConfig || {} }))
    .map((e) => e.id)
}

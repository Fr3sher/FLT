from ._schema_extend import persistent_table
from sqlalchemy import Integer, String, Text, DateTime, Float

video_bank = persistent_table('video_bank',
    db.Column('id', Integer, primary_key=True),
    db.Column('user_id', String(36), nullable=False, index=True, default='local'),
    db.Column('name', String(100), nullable=False),
    db.Column('source_path', Text, nullable=False),
    db.Column('pipeline_report', Text, nullable=True),
    db.Column('shot_threshold', Float, nullable=True),
    db.Column('created_at', DateTime, default=db.func.current_timestamp()),
    db.Column('updated_at', DateTime, default=db.func.current_timestamp(), onupdate=db.func.current_timestamp())
)

